"""
FraudLens — Indian UPI Model Evaluation Suite
=============================================
Performs an independent, chronological out-of-time evaluation of the
depth-constrained RandomForestClassifier pipeline on the synthetic Indian UPI baseline.

ACADEMIC SIMULATION NOTICE:
---------------------------
All metrics, confusion matrices, and risk thresholds generated by this evaluation
quantify algorithmic discriminative performance on the synthetic Indian UPI baseline.
They do NOT represent live bank network protection, NPCI operational efficacy,
or real-world financial cybercrime detection.
"""

import json
import os
import time
from datetime import datetime, timezone, timedelta
from typing import Dict, Any

import joblib
import numpy as np
import pandas as pd
from sklearn.metrics import (
    average_precision_score,
    confusion_matrix,
    f1_score,
    precision_score,
    recall_score,
    roc_auc_score,
)

BASE_DIR = os.path.dirname(os.path.abspath(__file__))
DATA_PATH = os.path.join(BASE_DIR, "dataset", "synthetic_baseline_inr.csv")
MODEL_PATH = os.path.join(BASE_DIR, "model", "fraudlens_india_pipeline.pkl")
REPORT_PATH = os.path.join(BASE_DIR, "evaluation_report_india.json")

IST_TZ = timezone(timedelta(hours=5, minutes=30))


def evaluate_indian_model(threshold: float = 0.50) -> Dict[str, Any]:
    """
    Run chronological out-of-time evaluation of the Indian model.
    """
    if not os.path.exists(MODEL_PATH):
        raise FileNotFoundError(f"Model file not found at: {MODEL_PATH}")

    if not os.path.exists(DATA_PATH):
        raise FileNotFoundError(f"Synthetic dataset not found at: {DATA_PATH}")

    print(f"Loading pipeline from: {MODEL_PATH}")
    pipeline = joblib.load(MODEL_PATH)
    model_file_size_mb = os.path.getsize(MODEL_PATH) / (1024 * 1024)

    print(f"Loading dataset from:  {DATA_PATH}")
    df = pd.read_csv(DATA_PATH)
    df = df.sort_values("timestamp").reset_index(drop=True)

    target = "is_fraud"
    n_total = len(df)
    n_train = int(n_total * 0.80)

    train_df = df.iloc[:n_train]
    test_df = df.iloc[n_train:]

    cutoff_timestamp = test_df["timestamp"].iloc[0]

    feature_cols = [
        "merchant_category",
        "transaction_type",
        "amount",
        "transaction_hour",
        "transaction_day",
        "transaction_month",
        "day_of_week",
        "is_weekend",
    ]

    X_train = train_df[feature_cols]
    y_train = train_df[target].astype(int)

    X_test = test_df[feature_cols]
    y_test = test_df[target].astype(int)

    # Determine class index for fraud
    clf = pipeline.named_steps["classifier"]
    classes = list(clf.classes_)
    fraud_idx = classes.index(1) if 1 in classes else 1

    # Predict probabilities on held-out test split
    print(f"\nComputing predictions on held-out chronological test partition (N={len(y_test):,})...")
    start_eval = time.time()
    y_prob = pipeline.predict_proba(X_test)[:, fraud_idx]
    y_pred = (y_prob >= threshold).astype(int)
    eval_latency = time.time() - start_eval

    # Compute classification metrics
    precision = float(precision_score(y_test, y_pred, zero_division=0))
    recall = float(recall_score(y_test, y_pred, zero_division=0))
    f1 = float(f1_score(y_test, y_pred, zero_division=0))
    pr_auc = float(average_precision_score(y_test, y_prob))
    roc_auc = float(roc_auc_score(y_test, y_prob))

    cm = confusion_matrix(y_test, y_pred, labels=[0, 1])
    tn, fp, fn, tp = int(cm[0, 0]), int(cm[0, 1]), int(cm[1, 0]), int(cm[1, 1])

    # Structure detailed evaluation report
    report: Dict[str, Any] = {
        "benchmark_metadata": {
            "title": "FraudLens Indian UPI Model Chronological Out-of-Time Benchmark",
            "model_type": "Pipeline(ColumnTransformer + RandomForestClassifier)",
            "model_file": os.path.basename(MODEL_PATH),
            "model_size_mb": round(model_file_size_mb, 4),
            "dataset_file": os.path.basename(DATA_PATH),
            "currency": "INR",
            "evaluation_timestamp": datetime.now(IST_TZ).isoformat(),
            "partitioning_strategy": "Chronological Out-of-Time (80% Train, 20% Held-Out Test)",
            "evaluation_disclosure": (
                "ACADEMIC SIMULATION NOTICE: All metrics evaluate discriminative performance "
                "on the synthetic Indian UPI transaction baseline. They do not represent live "
                "NPCI clearing network protection or verified commercial bank fraud detection."
            ),
        },
        "dataset_split": {
            "total_samples": n_total,
            "train_samples": len(train_df),
            "test_samples": len(test_df),
            "cutoff_timestamp": cutoff_timestamp,
            "train_date_range": {
                "start": str(train_df["timestamp"].iloc[0]),
                "end": str(train_df["timestamp"].iloc[-1]),
            },
            "test_date_range": {
                "start": str(test_df["timestamp"].iloc[0]),
                "end": str(test_df["timestamp"].iloc[-1]),
            },
            "train_class_distribution": {
                "legitimate": int((y_train == 0).sum()),
                "fraudulent": int((y_train == 1).sum()),
                "fraud_rate_percent": round(float((y_train == 1).mean() * 100), 2),
            },
            "test_class_distribution": {
                "legitimate": int((y_test == 0).sum()),
                "fraudulent": int((y_test == 1).sum()),
                "fraud_rate_percent": round(float((y_test == 1).mean() * 100), 2),
            },
        },
        "hyperparameters": {
            "n_estimators": clf.n_estimators,
            "max_depth": clf.max_depth,
            "min_samples_leaf": clf.min_samples_leaf,
            "class_weight": str(clf.class_weight),
            "random_state": clf.random_state,
        },
        "metrics": {
            "decision_threshold": threshold,
            "precision": round(precision, 4),
            "recall": round(recall, 4),
            "f1_score": round(f1, 4),
            "pr_auc": round(pr_auc, 4),
            "roc_auc": round(roc_auc, 4),
            "confusion_matrix": {
                "true_negatives": tn,
                "false_positives": fp,
                "false_negatives": fn,
                "true_positives": tp,
            },
        },
        "features_evaluated": feature_cols,
    }

    print("\n" + "=" * 60)
    print("CHRONOLOGICAL OUT-OF-TIME EVALUATION RESULTS")
    print("=" * 60)
    print(f"Model File Size:       {model_file_size_mb:.2f} MB")
    print(f"Decision Threshold:    {threshold:.2f}")
    print(f"Precision:             {precision * 100:.2f}%")
    print(f"Recall:                {recall * 100:.2f}%")
    print(f"F1 Score:              {f1:.4f}")
    print(f"PR-AUC (Avg Prec):     {pr_auc:.4f}")
    print(f"ROC-AUC:               {roc_auc:.4f}")
    print(f"True Positives:        {tp}")
    print(f"False Positives:       {fp}")
    print(f"False Negatives:       {fn}")
    print(f"True Negatives:        {tn}")

    # Serialize report to JSON
    with open(REPORT_PATH, "w", encoding="utf-8") as f:
        json.dump(report, f, indent=2)

    print(f"\nSerialized evaluation report to: {REPORT_PATH}")
    return report


if __name__ == "__main__":
    evaluate_indian_model()
